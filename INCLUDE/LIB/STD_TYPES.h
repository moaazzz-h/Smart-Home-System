#ifndef INCLUDE_LIB_STD_TYPES_H_
#define INCLUDE_LIB_STD_TYPES_H_
#define NULL    0
typedef unsigned char          u8;     // 1 byte = 8 bits
typedef signed char            s8;     // 1 byte = 8 bits

typedef unsigned short int     u16;    // 2 bytes = 16 bits
typedef signed short int       s16;    // 2 bytes = 16 bits

typedef unsigned long          u32;    // 4 bytes = 32 bits
typedef signed long            s32;    // 4 bytes = 32 bits

typedef unsigned long long int u64;    // 8 bytes = 64 bits
typedef signed long long int   s64;    // 8 bytes = 64 bits

typedef float                  f32;    // 4 bytes
typedef double                 f64;    // 8 bytes
typedef long double            f128;   // 16 bytes

#endif /* INCLUDE_LIB_STD_TYPES_H_ */
